from __future__ import annotations

import threading
import unittest
from unittest.mock import patch

from eva.automation import desktop
from eva.automation.tools.browser import BrowserSession


class DesktopLaunchSafetyTests(unittest.TestCase):
    def test_unknown_windows_app_never_falls_through_to_generic_shell_launcher(self):
        with patch("eva.automation.desktop.platform.system", return_value="Windows"), \
             patch("eva.automation.desktop._windows") as generic_launcher, \
             patch("eva.automation.desktop._try_open_native_app", return_value=None):
            result = desktop.execute("app_open", "invented-app-name")
        self.assertFalse(result["ok"])
        self.assertEqual(result["error_code"], "TARGET_NOT_REGISTERED")
        self.assertFalse(result["launch_requested"])
        self.assertIn("Microsoft Store fallback", result["error"])
        generic_launcher.assert_not_called()

    def test_missing_notepad_does_not_fall_through_to_store_or_browser(self):
        with patch("eva.automation.desktop.platform.system", return_value="Windows"), \
             patch("eva.automation.desktop._windows") as generic_launcher, \
             patch("eva.automation.desktop._try_open_native_app", return_value=None):
            result = desktop.execute("app_open", "notepad")
        self.assertFalse(result["ok"])
        self.assertEqual(result["error_code"], "APP_NOT_INSTALLED")
        self.assertFalse(result["launch_requested"])
        self.assertIn("No browser or Microsoft Store fallback was attempted", result["error"])
        generic_launcher.assert_not_called()

    def test_request_to_open_microsoft_store_for_search_is_rejected_without_launching_store(self):
        with patch("eva.automation.desktop.platform.system", return_value="Windows"), \
             patch("eva.automation.desktop._try_open_native_app", return_value=None), \
             patch("eva.automation.desktop._windows") as generic_launcher, \
             patch("eva.automation.desktop._open_browser_url") as browser_launcher:
            result = desktop.route_and_execute("open Microsoft Store to search something")
        self.assertFalse(result["ok"])
        self.assertEqual(result["error_code"], "TARGET_NOT_REGISTERED")
        generic_launcher.assert_not_called()
        browser_launcher.assert_not_called()

    def test_unknown_planner_target_is_rejected_without_browser_launch(self):
        # This is the registry-facing contract used by plans generated by the LLM.
        from eva.automation.service import AutomationService
        from tempfile import TemporaryDirectory
        from pathlib import Path

        with TemporaryDirectory() as tmp:
            service = AutomationService(allowed_roots=[Path(tmp)], audit_path=None,
                                        workflows_dir=Path(tmp) / "workflows",
                                        capability_gaps_path=Path(tmp) / "state" / "gaps.json",
                                        browser_headless=True)
            try:
                result = service.execute_tool("desktop.open_target", {"target": "some made-up app"})
                self.assertFalse(result.ok)
                self.assertEqual(result.error_code, "TARGET_NOT_REGISTERED")
                self.assertFalse(result.data.get("launch_requested", True))
            finally:
                service.close()

    def test_windows_core_apps_use_native_launch_without_powershell(self):
        for target, expected_exe in (("notepad", "notepad.exe"), ("calculator", "calc.exe")):
            with self.subTest(target=target), \
                 patch("eva.automation.desktop.platform.system", return_value="Windows"), \
                 patch.dict("eva.automation.desktop.os.environ", {"WINDIR": r"C:\Windows"}), \
                 patch("eva.automation.desktop.os.path.isfile", return_value=True), \
                 patch("eva.automation.desktop.shutil.which", return_value=None), \
                 patch("eva.automation.desktop.subprocess.Popen") as popen, \
                 patch("eva.automation.desktop._focus_notepad_window", return_value={"ok": True, "verified": True}) as focus, \
                 patch("eva.automation.desktop._ps") as powershell:
                result = desktop._try_open_native_app(target)
                self.assertTrue(result["ok"])
                self.assertEqual(result["method"], "native_process_launch")
                self.assertTrue(result["launch_requested"])
                self.assertEqual(result["path"].replace("/", "\\"), rf"C:\Windows\System32\{expected_exe}")
                popen.assert_called_once()
                powershell.assert_not_called()


    def test_legacy_natural_language_router_accepts_punctuation_after_notepad(self):
        with patch("eva.automation.desktop.execute", return_value={"ok": True}) as execute:
            result = desktop.route_and_execute("Open Notepad.")
        self.assertTrue(result["ok"])
        execute.assert_called_once_with("app_open", "notepad")

    def test_service_open_target_strips_terminal_punctuation_from_app_alias(self):
        from eva.automation.service import AutomationService
        from tempfile import TemporaryDirectory
        from pathlib import Path

        with TemporaryDirectory() as tmp:
            service = AutomationService(allowed_roots=[Path(tmp)], audit_path=None,
                                        workflows_dir=Path(tmp) / "workflows",
                                        capability_gaps_path=Path(tmp) / "state" / "gaps.json",
                                        browser_headless=True)
            try:
                with patch("eva.automation.desktop.execute", return_value={
                    "ok": True, "opened": "Notepad", "method": "native_process_launch",
                    "launch_requested": True, "verified": False,
                }) as launcher:
                    result = service.execute_tool("desktop.open_target", {"target": "Notepad."})
                self.assertTrue(result.ok, result.message)
                launcher.assert_called_once_with("app_open", "notepad")
            finally:
                service.close()


class BrowserThreadOwnershipTests(unittest.TestCase):
    def test_browser_sync_operations_are_dispatched_to_single_worker_thread(self):
        session = BrowserSession(headless=True)
        try:
            calling_thread = threading.get_ident()
            session._thread_probe = threading.get_ident
            first = session.run_serialized("_thread_probe")
            second = session.run_serialized("_thread_probe")
            self.assertNotEqual(first, calling_thread)
            self.assertEqual(first, second)
            self.assertEqual(session._worker_thread_id, first)
        finally:
            session.close()

    def test_closed_browser_session_refuses_later_calls_cleanly(self):
        session = BrowserSession(headless=True)
        session.close()
        with self.assertRaises(Exception) as raised:
            session.run_serialized("navigate", "https://example.com")
        self.assertEqual(getattr(raised.exception, "code", None), "BROWSER_SESSION_CLOSED")
